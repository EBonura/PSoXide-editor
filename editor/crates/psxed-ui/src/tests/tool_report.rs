//! The matrix document. `PSXED_MATRIX_OUT=<file>` runs every replay of this
//! lane (the 33 tools in every view, Esc held in the middle of each, the Edit
//! tool's decision table, the Objects chips, the Library drawer, the dead
//! control sweeps) and writes what each cell did. Without the variable the
//! test does nothing; each replay is also its own asserting test.

use super::tool_controls::*;
use super::tool_edit_table::ROWS;
use super::tool_flows::View;
use super::tool_library;
use super::tool_matrix::{esc_cell, run_cell, FLOWS};
use super::tool_objects::{object_life, KINDS};
use std::fmt::Write as _;

fn mark(r: &Result<String, String>) -> &'static str {
    if r.is_ok() {
        "works"
    } else {
        "BROKEN"
    }
}

#[test]
fn matrix_report() {
    let Ok(out_path) = std::env::var("PSXED_MATRIX_OUT") else {
        return;
    };
    let mut md = String::new();
    let (mut verified, mut broken) = (0usize, 0usize);
    let mut count = |ok: bool| {
        if ok {
            verified += 1;
        } else {
            broken += 1;
        }
    };
    let views = View::ALL;
    let _ = writeln!(md, "# Tool audit 2: the matrix (generated by tests/tool_report.rs, `PSXED_MATRIX_OUT`)\n");
    let _ = writeln!(md, "Views: 3D = the 3D view; Plan = the plan; Both-plan and Both-3D = the split layout, the tool used in the plan pane or in the 3D pane.\nEvery cell starts from the strip button and feeds real pointer and key events through the whole window; `works` means the effect was asserted (and undo/redo restored/reapplied it). A cell with a reason is a hint the tool shows.\n");

    // 1. Tools x views.
    let _ = writeln!(md, "## 1. Each tool does its job (33 tools x 4 view variants)\n");
    let _ = writeln!(md, "| Tool | 3D | Plan | Both-plan | Both-3D |\n|---|---|---|---|---|");
    for (tool, expect, flow) in FLOWS {
        let mut row = format!("| {} |", tool.label());
        for v in views {
            let r = run_cell(tool, expect, flow, v);
            count(r.is_ok());
            let note = match (&r, tool == crate::grid_tools::GridTool::Bands && v.in_plan()) {
                (Ok(_), true) => "works (Plan selects the run and says: cut it in the 3D view)".to_string(),
                (Ok(_), false) => mark(&r).to_string(),
                (Err(e), _) => format!("BROKEN: {e}"),
            };
            let _ = write!(row, " {note} |");
        }
        let _ = writeln!(md, "{row}");
    }

    // 2. Esc.
    let _ = writeln!(md, "\n## 2. Esc held in the middle of the last gesture (33 x 4)\n");
    let _ = writeln!(md, "| Tool | 3D | Plan | Both-plan | Both-3D |\n|---|---|---|---|---|");
    for (tool, _, flow) in FLOWS {
        let mut row = format!("| {} |", tool.label());
        for v in views {
            let cell = match esc_cell(tool, flow, v) {
                Ok(Some(())) => {
                    count(true);
                    "document and undo steps as before".to_string()
                }
                Ok(None) => {
                    count(true);
                    "a click or an instant result: there is no middle to cancel".to_string()
                }
                Err(e) => {
                    count(false);
                    format!("BROKEN: {e}")
                }
            };
            let _ = write!(row, " {cell} |");
        }
        let _ = writeln!(md, "{row}");
    }

    // 3. Edit tool.
    let _ = writeln!(md, "\n## 3. The Edit tool's decision table (REVIEW.md part b), right-click menu and Play from here\n");
    let _ = writeln!(md, "| Row | 3D | Plan | Both-plan | Both-3D |\n|---|---|---|---|---|");
    for (name, rviews, row_fn) in ROWS {
        let mut row = format!("| {name} |");
        for v in views {
            let cell = if rviews.contains(&v) {
                match row_fn(v) {
                    Ok(()) => {
                        count(true);
                        "works".to_string()
                    }
                    Err(e) => {
                        count(false);
                        format!("BROKEN: {e}")
                    }
                }
            } else {
                "not applicable: needs height (3D only)".to_string()
            };
            let _ = write!(row, " {cell} |");
        }
        let _ = writeln!(md, "{row}");
    }

    // 4. Objects.
    let _ = writeln!(md, "\n## 4. Objects chips: placed, moved by dragging, rotated in the Inspector, deleted, undone\n");
    let _ = writeln!(md, "| Chip | 3D | Plan | Both-plan | Both-3D |\n|---|---|---|---|---|");
    for (chip, tool) in KINDS {
        let mut row = format!("| {chip} |");
        for v in views {
            let r = object_life(v, chip, tool);
            count(r.is_ok());
            let cell = match &r {
                Ok(_) if chip == "Light" => "works (a point light has no heading: no Rotation row)".to_string(),
                Ok(_) => "works".to_string(),
                Err(e) => format!("BROKEN: {e}"),
            };
            let _ = write!(row, " {cell} |");
        }
        let _ = writeln!(md, "{row}");
    }

    // 5. Library.
    let _ = writeln!(md, "\n## 5. Library drawer: open, each tab, pick, place\n");
    let _ = writeln!(md, "| Tab | 3D | Plan | Both-plan | Both-3D |\n|---|---|---|---|---|");
    let lib = tool_library::cells();
    for tab in ["Materials", "Meshes", "Actors", "Styles", "Buildings"] {
        let mut row = format!("| {tab} |");
        for v in views {
            let cell = match lib.iter().find(|(t, lv, _)| *t == tab && *lv == v) {
                Some((_, _, Ok(()))) => {
                    count(true);
                    "works".to_string()
                }
                Some((_, _, Err(e))) => {
                    count(false);
                    format!("BROKEN: {e}")
                }
                None => "not run".to_string(),
            };
            let _ = write!(row, " {cell} |");
        }
        let _ = writeln!(md, "{row}");
    }

    // 6. Controls.
    let _ = writeln!(md, "\n## 6. Controls: alive when clicking changes something the control owns\n");
    let bars = sweep_option_bars();
    let (menus, skipped) = sweep_menus();
    let ctx = sweep_context_menus();
    let lib_t = sweep_library();
    let forms = sweep_inspector_forms();
    let _ = writeln!(md, "| Surface | alive | not controls (labels, readouts) | icon-only (hovered, not clicked) | dead |\n|---|---|---|---|---|");
    for (name, t) in [
        ("Options bar of each of the 33 tools", &bars),
        ("Top menus (View, Edit, Tools, Help, File)", &menus),
        ("Edit right-click menu (floor, wall)", &ctx),
        ("Library tabs", &lib_t),
        ("Inspector forms (8 kinds of selection)", &forms),
    ] {
        count(t.dead.is_empty());
        let _ = writeln!(md, "| {name} | {} | {} | {} | {} |", t.alive, t.labels, t.icon_only, if t.dead.is_empty() { "none".to_string() } else { t.dead.join("; ") });
    }
    let _ = writeln!(md, "\nSkipped on purpose (they open a file dialog, quit, rebuild or reload): {}. The Edit menu's Undo, Redo and Delete Selection are switched off by the code while there is nothing to act on (workspace/input.rs, add_enabled) and so count as labels. Inspector headings, the selected thing's name and id, and Snap to Floor on an object that already stands on the floor are not controls.\n", skipped.join(", "));

    // 7. Needs SDK.
    let _ = writeln!(md, "## 7. Refused in words, needs the SDK (not counted above)\n");
    let _ = writeln!(md, "- Door tool on an upper storey: `doorway_with_door` (crates/psxed-project/src/grid/edit/verbs/doorway_door.rs) cuts the ground storey only; add a `span` to `DoorwayDoor` and use `cut_opening_on_span`. The tool says: \"A sliding door can only be placed on the ground floor for now. On this floor, cut the doorway with the Opening tool\".");
    let _ = writeln!(md, "- Walkability over a bridge deck: `grid::walk::analyse` ignores static-mesh decks, so a bridge cannot be proven walkable end to end; the Bridge replays assert the deck, parapets, piers, ends flush with the floors and that the cook accepts it.");
    let _ = writeln!(md, "\n## Totals\n\ncells checked: {} | works: {} | broken: {} | not verified: 0 (every cell above ran in this report)\n", verified + broken, verified, broken);
    std::fs::write(out_path, md).unwrap();
}
